// ── Format 1: slug-map (no extra spaces) ─────────────
function serializeFmt1(rows) {
  const n = rows.length;
  let out = `a:${n}:{`;
  rows.forEach(r => {
    const sl = r.src.length;
    const tl = r.url.length;
    out += `s:${sl}:"${r.src}";a:2:{`;
    out += `s:3:"url";s:${tl}:"${r.url}";`;
    out += `s:4:"type";i:${r.type};`;
    out += `}`;
  });
  out += `}`;
  return out;
}

// ── Format 2: indexed array with origin + format ──────
function serializeFmt2(rows) {
  const n = rows.length;
  let out = `a:${n}:{`;
  rows.forEach((r, i) => {
    const ol = r.src.length;
    const ul = r.url.length;
    out += `i:${i};a:4:{`;
    out += `s:6:"origin";s:${ol}:"${r.src}";`;
    out += `s:3:"url";s:${ul}:"${r.url}";`;
    out += `s:4:"type";i:${r.type};`;
    out += `s:6:"format";s:5:"plain";`;
    out += `}`;
  });
  out += `}`;
  return out;
}

// ── table ─────────────────────────────────────────────
function getFiltered() {
  const q = document.getElementById('q').value.toLowerCase().trim();
  const ft = document.getElementById('ft').value;
  return data.filter(r => {
    const mq = !q || r.src.toLowerCase().includes(q) || r.url.toLowerCase().includes(q);
    const mt = !ft || String(r.type) === ft;
    return mq && mt;
  });
}

