// ── selection ─────────────────────────────────────────
function toggleSel(id, cb) { cb.checked ? sel.add(id) : sel.delete(id); render(); }
function toggleAll(cb) { getFiltered().forEach(r => cb.checked ? sel.add(r.id) : sel.delete(r.id)); render(); }
function clearSel() { sel.clear(); render(); }

// ── bulk add ──────────────────────────────────────────
function saveBulk() {
  const lines = document.getElementById('bulkPaste').value.trim().split('\n').filter(Boolean);
  if (!lines.length) { toast('Nothing to import', 'err'); return; }
  let added = 0, updated = 0, skipped = 0;
  lines.forEach(line => {
    const parts = line.split(',').map(s => s.trim());
    const src = parts[0]; if (!src) { skipped++; return; }
    const url = parts[1] || '';
    const type = parseInt(parts[2]) || 301;
    const ex = data.find(r => r.src === src);
    if (ex) { ex.url = url; ex.type = type; updated++; }
    else { data.push({ id: nextId++, src, url, type, isNew: true }); added++; }
  });
  document.getElementById('bulkPaste').value = '';
  render();
  setPanel('out');
  toast(`Added ${added}, updated ${updated}${skipped ? ' (' + skipped + ' skipped)' : ''}`, 'ok');
}

// ── edit ──────────────────────────────────────────────
function openEdit(id) {
  const r = data.find(x => x.id === id); editId = id;
  document.getElementById('eSrc').value = r.src;
  document.getElementById('eTgt').value = r.url;
  document.getElementById('eType').value = r.type;
  document.getElementById('editOv').classList.add('open');
}
function saveEdit() {
  const r = data.find(x => x.id === editId);
  r.src = document.getElementById('eSrc').value.trim();
  r.url = document.getElementById('eTgt').value.trim();
  r.type = parseInt(document.getElementById('eType').value);
  closeEdit(); render(); toast('Saved', 'ok');
}
function closeEdit() { document.getElementById('editOv').classList.remove('open'); editId = null; }

// ── delete ────────────────────────────────────────────
function openConf(id) {
  delId = id;
  const r = data.find(x => x.id === id);
  document.getElementById('confMsg').textContent = `Delete "${r.src}"? This cannot be undone.`;
  document.getElementById('confOv').classList.add('open');
}
function doDelete() { data = data.filter(r => r.id !== delId); sel.delete(delId); closeConf(); render(); toast('Deleted', 'ok'); }
function closeConf() { document.getElementById('confOv').classList.remove('open'); delId = null; }
function bulkDel() { const c = sel.size; data = data.filter(r => !sel.has(r.id)); sel.clear(); render(); toast(`Deleted ${c} entries`, 'ok'); }

// ── panels ────────────────────────────────────────────
function setPanel(p) {
  document.getElementById('outPanel').style.display = p === 'out' ? 'flex' : 'none';
  document.getElementById('addPanel').style.display = p === 'add' ? 'flex' : 'none';
  document.querySelectorAll('.ptab').forEach((b, i) => b.classList.toggle('active', (i === 0 && p === 'out') || (i === 1 && p === 'add')));
  document.getElementById('panelLabel').textContent = p === 'out' ? 'Serialized output' : 'Bulk add entries';
}

// ── toast ─────────────────────────────────────────────
