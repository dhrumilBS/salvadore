function copyOut(n) {
  const txt = document.getElementById(`outBox${n}`).textContent;
  navigator.clipboard.writeText(txt).then(() => {
    const el = document.getElementById(`cok${n}`);
    el.style.display = 'inline';
    setTimeout(() => el.style.display = 'none', 2000);
    toast('Copied!', 'ok');
  });
}

function dl(txt, name) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(new Blob([txt], { type: 'text/plain' }));
  a.download = name;
  a.click();
}

function saveTxt(n) {
  const txt = document.getElementById(`outBox${n}`).textContent;
  const name = n === 1 ? 'redirects-format1-slugmap.txt' : 'redirects-format2-indexed.txt';
  dl(txt, name);
  toast(`Saved ${name}`, 'ok');
}

